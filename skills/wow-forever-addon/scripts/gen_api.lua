-- Generate references/forever-api-index.md and templates/luacheck/forever-std.lua
-- from a Gethe/wow-ui-source checkout (branch: forever).
-- usage: luajit gen_api.lua <wow-ui-source> <skill-dir> <commit> <date>
local SRC, SK, COMMIT, DATE = arg[1], arg[2], arg[3] or "unknown", arg[4] or os.date("!%Y-%m-%d")
assert(SRC and SK, "usage: luajit gen_api.lua <wow-ui-source> <skill-dir> [commit] [date]")

-- C-side / Lua-extension globals absent from the generated docs. Extend by hand when lint misses a real API.
local EXTRA_GLOBALS = { "CreateFrame", "UIParent", "SlashCmdList", "strsplit", "strtrim", "strjoin",
  "strlower", "strupper", "strlen", "strsub", "strfind", "strmatch", "strrep", "strrev", "strbyte", "strchar",
  "gsub", "format", "tinsert", "tremove", "wipe", "tContains", "sort", "getn", "bit", "securecall",
  "issecurevariable", "hooksecurefunc", "InCombatLockdown", "GetTime", "GetBuildInfo", "debugstack",
  "debugprofilestop", "geterrorhandler", "seterrorhandler", "date", "time", "floor", "ceil", "abs", "max",
  "min", "mod", "random", "sqrt", "fastrandom", "GetLocale" }

local function lines(cmd)
  local t, p = {}, assert(io.popen(cmd))
  for l in p:lines() do t[#t + 1] = l end
  p:close()
  return t
end

local function sorted(set)
  local t = {}
  for k in pairs(set) do t[#t + 1] = k end
  table.sort(t)
  return t
end

-- 1) Blizzard_APIDocumentationGenerated
local systems = {}
APIDocumentation = { AddDocumentationTable = function(_, t) systems[#systems + 1] = t end }
-- Some doc files read Enum.* / Constants.* while building their tables; auto-vivify stand-ins.
local function autoviv()
  local mt = {}
  mt.__index = function(t, k) local v = autoviv(); rawset(t, k, v); return v end
  mt.__add = function() return 0 end
  mt.__sub, mt.__mul, mt.__unm = mt.__add, mt.__add, mt.__add
  return setmetatable({}, mt)
end
Enum, Constants = autoviv(), autoviv()
local docdir = SRC .. "/Interface/AddOns/Blizzard_APIDocumentationGenerated"
local skipped = 0
for _, f in ipairs(lines('ls "' .. docdir .. '"/*.lua')) do
  local chunk, err = loadfile(f)
  local ok, perr = false, nil
  if chunk then ok, perr = pcall(chunk) end
  if not ok then
    skipped = skipped + 1
    io.stderr:write("skip ", f, ": ", tostring(err or perr), "\n")
  end
end
assert(#systems > 0, "no documentation tables loaded from " .. docdir)

local ns, docGlobals, events, fxGlobals = {}, {}, {}, {}
for _, s in ipairs(systems) do
  for _, fn in ipairs(s.Functions or {}) do
    if s.Namespace then
      ns[s.Namespace] = ns[s.Namespace] or {}
      ns[s.Namespace][fn.Name] = true
    else
      docGlobals[fn.Name] = true
    end
  end
  for _, ev in ipairs(s.Events or {}) do
    if ev.LiteralName then events[ev.LiteralName] = s.Namespace or s.Name end
  end
end

-- 2) FrameXML globals: top-level `function Name(` / `Name =` in Lua, `name="X"` in XML
for _, f in ipairs(lines('find "' .. SRC .. '/Interface" -name "*.lua"')) do
  for l in io.lines(f) do
    local n = l:match("^function%s+([%a_][%w_]*)%s*%(") or l:match("^([%a_][%w_]*)%s*=[^=]")
    if n and n ~= "local" and not ns[n] then fxGlobals[n] = true end
  end
end
for _, f in ipairs(lines('find "' .. SRC .. '/Interface" -name "*.xml"')) do
  local fh = io.open(f)
  local s = fh:read("*a")
  fh:close()
  for n in s:gmatch('%sname="([%a_][%w_]*)"') do fxGlobals[n] = true end
end
for _, n in ipairs(EXTRA_GLOBALS) do fxGlobals[n] = true end

-- 3) never-emit list from forever-api-notes.md (between the markers), reported against what exists
local nf = assert(io.open(SK .. "/references/forever-api-notes.md"))
local notes = nf:read("*a")
nf:close()
local block = notes:match("<!%-%- never%-emit:start %-%->(.-)<!%-%- never%-emit:end %-%->") or ""
local never = {}
for n in block:gmatch("\n%- `([%w_%.]+)`") do never[#never + 1] = n end
for _, n in ipairs(never) do
  local where = docGlobals[n] and "DOCS (real API - remove from never-emit!)"
    or fxGlobals[n] and "FrameXML shim (keep; note as deprecated)"
    or "absent"
  io.stdout:write(("never-emit %-32s %s\n"):format(n, where))
  docGlobals[n], fxGlobals[n] = nil, nil
  local nsName, field = n:match("^([%w_]+)%.([%w_]+)$")
  if nsName and ns[nsName] then ns[nsName][field] = nil end
end

-- 4) luacheck std
local function q(s) return ('"%s"'):format(s) end
local out = {
  ("-- GENERATED by gen_api.lua from Gethe/wow-ui-source@forever %s (%s). Do not edit.\n"):format(COMMIT, DATE),
  "stds.forever = { read_globals = {\n  Enum = { other_fields = true },\n",
}
for _, n in ipairs(sorted(ns)) do
  local fs = {}
  for _, f in ipairs(sorted(ns[n])) do fs[#fs + 1] = q(f) end
  out[#out + 1] = ("  %s = { fields = { %s } },\n"):format(n, table.concat(fs, ", "))
end
local all = {}
for k in pairs(docGlobals) do all[k] = true end
for k in pairs(fxGlobals) do all[k] = true end
all.Enum = nil
for _, g in ipairs(sorted(all)) do
  if not ns[g] then out[#out + 1] = "  " .. q(g) .. ",\n" end
end
out[#out + 1] = "} }\n"
local fh = assert(io.open(SK .. "/templates/luacheck/forever-std.lua", "w"))
fh:write(table.concat(out))
fh:close()

-- 5) index markdown: ToC, one section per namespace, doc globals, events
local md = {
  "# Forever API index\n\nGENERATED by `scripts/gen-api.sh` from Gethe/wow-ui-source@forever `" .. COMMIT
    .. "` (" .. DATE .. "). Do not edit; rerun the script.\n\n",
  "Names only. For signatures read the matching `*Documentation.lua` in that branch. Never-emit names are removed.\n\n## Contents\n",
}
for _, n in ipairs(sorted(ns)) do md[#md + 1] = ("- [%s](#%s)\n"):format(n, n:lower()) end
md[#md + 1] = "- [Global functions (documented)](#global-functions-documented)\n- [Events](#events)\n"
for _, n in ipairs(sorted(ns)) do
  md[#md + 1] = ("\n## %s\n%s\n"):format(n, table.concat(sorted(ns[n]), ", "))
end
md[#md + 1] = "\n## Global functions (documented)\n" .. table.concat(sorted(docGlobals), ", ") .. "\n"
md[#md + 1] = ("\nFrameXML/C globals allowed by lint: %d (see templates/luacheck/forever-std.lua)\n"):format(#sorted(fxGlobals))
md[#md + 1] = "\n## Events\n"
for _, e in ipairs(sorted(events)) do md[#md + 1] = ("- `%s` (%s)\n"):format(e, events[e]) end
fh = assert(io.open(SK .. "/references/forever-api-index.md", "w"))
fh:write(table.concat(md))
fh:close()

print(("namespaces=%d docGlobals=%d frameXML=%d events=%d skippedDocs=%d"):format(
  #sorted(ns), #sorted(docGlobals), #sorted(fxGlobals), #sorted(events), skipped))
